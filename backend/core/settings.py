def _smart_cast(value: str):
    s = value.strip()

    # boolean
    if s.lower() in ("true", "1", "yes", "on"):
        return True
    if s.lower() in ("false", "0", "no", "off"):
        return False

    # int
    try:
        return int(s)
    except ValueError:
        pass

    # float
    try:
        return float(s)
    except ValueError:
        pass

    # lista simples por vírgula (se não for JSON explícito)
    if "," in s and not (s.startswith("{") or s.startswith("[")):
        return [item.strip() for item in s.split(",")]

    # JSON (dict/list/null/true/false/num/str)
    try:
        return json.loads(s)
    except Exception:
        return s  # string pura


