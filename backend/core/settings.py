    env = (os.environ.get('APP_VERSION') or '').strip()
    if env:
        return env
    for base in (Path(__file__).resolve().parent.parent,
                 Path(__file__).resolve().parent.parent.parent):
        arquivo = base / 'VERSION'
        try:
            texto = arquivo.read_text().strip()
            if texto:
                return texto
        except OSError:
            continue
    return '0.0.0'


