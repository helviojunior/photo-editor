def _is_raw_string_setting(key: str) -> bool:
    """Segredos e chaves NUNCA passam pelo _smart_cast.

    O _smart_cast transforma qualquer string com virgula em lista (e digitos em
    int, etc.). Uma SECRET_KEY sorteada contendo virgula virava ``list``, e a
    derivacao de chaves quebrava com "'list' object has no attribute
    'encode'". Segredo e sempre texto opaco.
    """
    return key.endswith((
        "SECRET", "SECRET_KEY", "PASSWORD", "PASSPHRASE", "TOKEN", "KEY", "KEY_PATH",
    ))


# 2) Promove as variáveis MAIÚSCULAS a settings do módulo.
#    O valor efetivo vem de os.environ (SO/launcher manda mais que o arquivo);
#    o .env só entra como default — ver o setdefault acima.
for key, val in (_env or {}).items():
    if not key or not key.isupper():
        continue
    raw = os.environ.get(key, val)
    globals()[key] = raw if _is_raw_string_setting(key) else _smart_cast(raw)

# Settings que o Django exige como LISTA: um valor so, sem virgula, o
